import type { Metadata } from "next"

import { EmailPreviews } from "@/components/design-guide/email-previews"
import { PageHeader } from "@/components/ds/page-header"
import { emailTemplateCatalog } from "@/emails/catalog"

// The Emails section of the style guide, as its own address.
//
// It is a sub-route rather than a section of /design because it renders fourteen
// full documents inside sandboxed frames: keeping it off the main guide keeps
// that page quick to open. It sits on the admin host, so it is behind the same
// staff permission guard and two-factor wrapper as the rest of the guide
// (app/hosts/admin/layout.tsx), and it is noindex for the same reason.
//
// The templates are rendered here, on the server, from the same functions that
// send them. Nothing is fetched, and the frames run no scripts.

export const metadata: Metadata = {
  title: "Emails | Affilova Admin",
  robots: {
    index: false,
    follow: false,
    nocache: true,
  },
}

export default function EmailStyleGuidePage() {
  const entries = emailTemplateCatalog()

  return (
    <>
      <PageHeader
        title="Emails"
        description="Every message Affilova sends, rendered from the template that sends it, at 600px and 360px, with its plain-text version."
        breadcrumbs={[
          { label: "Admin", href: "/" },
          { label: "Design system", href: "/design" },
          { label: "Emails" },
        ]}
      />

      <p className="mb-8 max-w-reading text-dense text-text-muted">
        The frames are sandboxed with no scripts, so nothing in a message can run here. A product
        title is a vendor&apos;s words: it is escaped by React and it is shown in a frame that can do
        nothing. The plain-text version is the one the sender posts alongside the HTML, generated by
        the same renderer.
      </p>

      <EmailPreviews entries={entries} />
    </>
  )
}
